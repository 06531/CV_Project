// Stamps every portfolio image with a fingerprint of its own bytes, so that
// replacing one actually replaces it everywhere.
//
// The problem this exists for is not theoretical. `public/portfolio/otto-1.jpg`
// had a former employer's internal address printed on it; the page was
// re-rendered with the link masked out, and the old picture kept being served
// anyway — because `/_next/image?url=/portfolio/otto-1.jpg&w=1080&q=75` says
// nothing about *which* otto-1.jpg, and every layer in front of it had already
// answered that question. Next's optimiser caches per (source, width, quality,
// Accept), so the AVIF a browser asks for and the JPEG a curl asks for are
// different entries that expire independently: the JPEG came back clean while
// the AVIF on screen was still the old one. Vercel's edge cache and the reader's
// own browser both key the same way.
//
// A content hash in the query string changes all of those keys at once. The old
// entries are not evicted — they simply stop being addressable, which for a
// picture that should never be served again is the stronger guarantee.
//
// One token for the whole directory rather than one per file, because the query
// has to be declared in `images.localPatterns` for Next to optimise it at all,
// and that list is capped at 25 entries — fewer than there are screenshots. The
// alternative, a pattern with `search` left off, would let a stranger ask the
// optimiser for `otto-1.jpg?x=1`, `?x=2`, … forever. So: replacing any one
// image re-versions all of them. That is a few megabytes of re-optimising on a
// change that happens a couple of times a year, and it errs the safe way — when
// the reason for the change is that something should not have been on screen,
// leaving the other twenty-four addressable is not a saving worth having.
//
// Runs after whatever produced the images (render-pdf-pages, capture-schedule);
// it reads the directory rather than being told, so it cannot fall behind them.
//
// Usage: node scripts/version-assets.mjs

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(root, 'public', 'portfolio');
const OUT = path.join(root, 'src', 'data', 'asset-versions.ts');

/** Every image under public/portfolio, as the web path that `cv.ts` uses. */
function walk(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) return walk(full);
    return /\.(jpe?g|png|webp|avif)$/i.test(entry) ? [full] : [];
  });
}

const files = walk(DIR).sort();
if (files.length === 0) {
  console.error(`no images under ${path.relative(root, DIR)} — run \`npm run assets:pdf\` first`);
  process.exit(1);
}

// Paths go into the digest alongside the bytes, so that renaming a screenshot
// counts as a change even when its contents did not.
const digest = createHash('sha256');
for (const file of files) {
  digest.update(path.relative(root, file).split(path.sep).join('/'));
  digest.update(readFileSync(file));
}
// Eight hex characters: enough that two different sets colliding is not worth
// thinking about, short enough to read in a URL.
const version = digest.digest('hex').slice(0, 8);

writeFileSync(
  OUT,
  `// Generated by \`npm run assets:version\` — do not edit by hand.
//
// A fingerprint of every file under public/portfolio, taken together.
// \`assetSrc()\` in cv.ts appends it to each image path so that a replaced
// picture gets a URL no cache anywhere has an answer for, and next.config.ts
// declares the same token so Next will optimise those URLs at all.
// See scripts/version-assets.mjs for why it is one token and not one per file.
//
// Covers ${files.length} images.

export const PORTFOLIO_VERSION = '${version}';
`,
  'utf8',
);

console.log(
  `  version ${files.length} images -> ${path.relative(root, OUT)} (v=${version})`,
);
